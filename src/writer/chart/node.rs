// Chart ranges: "=Sheet1!$A$1:$A$5" or (sheet, first_row, first_col, last_row, last_col).
// ---------------------------------------------------------------------------

/// A chart data range, series name or label reference.
///
/// * `"=Sheet1!$A$1:$A$5"`: a formula (a plain string without `!` is a
///   literal name where names are accepted);
/// * `("Sheet1", row, col)`: one cell;
/// * `("Sheet1", first_row, first_col, last_row, last_col)`: a range.
#[derive(Clone, Debug, PartialEq)]
pub enum RangeSpec {
    Text(String),
    Cell(String, u32, u16),
    Range(String, u32, u16, u32, u16),
}

impl RangeSpec {
    pub fn to_rust(&self) -> RChartRange {
        match self {
            RangeSpec::Text(text) => RChartRange::new_from_string(text),
            RangeSpec::Cell(sheet, row, col) => {
                RChartRange::new_from_range(sheet, *row, *col, *row, *col)
            }
            RangeSpec::Range(sheet, r1, c1, r2, c2) => {
                RChartRange::new_from_range(sheet, *r1, *c1, *r2, *c2)
            }
        }
    }

    /// A readable formula for this reference ("" for an empty literal).
    pub fn display(&self) -> String {
        let quote = rust_xlsxwriter::utility::quote_sheet_name;
        match self {
            RangeSpec::Text(text) => text.clone(),
            RangeSpec::Cell(sheet, row, col) => {
                format!("={}!{}", quote(sheet), cell_name(*row, *col, true, true))
            }
            RangeSpec::Range(sheet, r1, c1, r2, c2) => format!(
                "={}!{}:{}",
                quote(sheet),
                cell_name(*r1, *c1, true, true),
                cell_name(*r2, *c2, true, true)
            ),
        }
    }
}

fn extract_index(value: &Bound<'_, PyAny>, what: &str, limit: u32) -> PyResult<u32> {
    let index: i64 = value
        .extract()
        .map_err(|_| PyTypeError::new_err(format!("a chart range {what} must be an int")))?;
    if !(0..limit as i64).contains(&index) {
        return Err(range_err(format!(
            "chart range {what} {index} is outside 0..{limit}"
        )));
    }
    Ok(index as u32)
}

impl<'a, 'py> FromPyObject<'a, 'py> for RangeSpec {
    type Error = PyErr;

    fn extract(obj: Borrowed<'a, 'py, PyAny>) -> Result<Self, Self::Error> {
        if let Ok(text) = obj.cast::<PyString>() {
            return Ok(RangeSpec::Text(text.to_str()?.to_string()));
        }
        if let Ok(tuple) = obj.cast::<PyTuple>() {
            let items: Vec<Bound<'py, PyAny>> = tuple.iter().collect();
            let sheet: String = match items.first() {
                Some(first) => first.extract().map_err(|_| {
                    PyTypeError::new_err(
                        "the first item of a chart range tuple must be the sheet name",
                    )
                })?,
                None => String::new(),
            };
            if (items.len() == 3 || items.len() == 5) && sheet.is_empty() {
                return Err(param_err(
                    "a chart range tuple needs a non-empty sheet name",
                ));
            }
            match items.len() {
                3 => {
                    let row = extract_index(&items[1], "row", MAX_ROWS)?;
                    let col = extract_index(&items[2], "column", MAX_COLS as u32)? as u16;
                    return Ok(RangeSpec::Cell(sheet, row, col));
                }
                5 => {
                    let r1 = extract_index(&items[1], "row", MAX_ROWS)?;
                    let c1 = extract_index(&items[2], "column", MAX_COLS as u32)? as u16;
                    let r2 = extract_index(&items[3], "row", MAX_ROWS)?;
                    let c2 = extract_index(&items[4], "column", MAX_COLS as u32)? as u16;
                    if r1 > r2 || c1 > c2 {
                        return Err(range_err(format!(
                            "chart range {}{}:{}{} is reversed: the first cell must be above/left of the last",
                            col_to_name(c1),
                            r1 + 1,
                            col_to_name(c2),
                            r2 + 1
                        )));
                    }
                    return Ok(RangeSpec::Range(sheet, r1, c1, r2, c2));
                }
                _ => {}
            }
        }
        Err(PyTypeError::new_err(format!(
            "expected a range string such as '=Sheet1!$A$1:$A$5', a (sheet, row, col) tuple or a \
             (sheet, first_row, first_col, last_row, last_col) tuple, not {}",
            obj.get_type().name()?
        )))
    }
}

impl<'py> IntoPyObject<'py> for RangeSpec {
    type Target = PyAny;
    type Output = Bound<'py, PyAny>;
    type Error = PyErr;

    fn into_pyobject(self, py: Python<'py>) -> Result<Self::Output, Self::Error> {
        match self {
            RangeSpec::Text(text) => text.into_bound_py_any(py),
            RangeSpec::Cell(sheet, row, col) => (sheet, row, col).into_bound_py_any(py),
            RangeSpec::Range(sheet, r1, c1, r2, c2) => {
                (sheet, r1, c1, r2, c2).into_bound_py_any(py)
            }
        }
    }
}

