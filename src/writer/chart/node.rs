/// A nested chart object, created lazily and returned live.
pub struct Slot<T> {
    cell: PyOnceLock<Py<T>>,
    assigned: bool,
}

impl<T> Default for Slot<T> {
    fn default() -> Self {
        Slot {
            cell: PyOnceLock::new(),
            assigned: false,
        }
    }
}

impl<T: Node> Slot<T> {
    /// The live object (created on first access).
    pub fn get(&self, py: Python<'_>) -> PyResult<Py<T>> {
        let obj = self.cell.get_or_try_init(py, || Py::new(py, T::fresh()))?;
        Ok(obj.clone_ref(py))
    }

    /// Replace the object (`None` resets the slot to an unused default).
    pub fn put(&mut self, py: Python<'_>, obj: Option<Py<T>>) {
        self.cell = PyOnceLock::new();
        self.assigned = false;
        if let Some(obj) = obj {
            let _ = self.cell.set(py, obj);
            self.assigned = true;
        }
    }

    /// Assign a Python value (see [`Node::coerce`]); `None` resets the slot.
    pub fn assign(&mut self, value: Option<&Bound<'_, PyAny>>) -> PyResult<()> {
        match value {
            None => {
                self.cell = PyOnceLock::new();
                self.assigned = false;
            }
            Some(value) => {
                let obj = T::coerce(value)?;
                self.put(value.py(), obj);
            }
        }
        Ok(())
    }

    /// True if the object was assigned or has non-default settings.
    pub fn active(&self, py: Python<'_>) -> bool {
        match self.cell.get(py) {
            None => false,
            Some(obj) => {
                self.assigned
                    || obj
                        .try_borrow(py)
                        .map(|o| !o.is_default(py))
                        .unwrap_or(true)
            }
        }
    }

    /// Run `f` on the object if it exists.
    pub fn with<R>(
        &self,
        py: Python<'_>,
        f: impl FnOnce(&T) -> PyResult<R>,
    ) -> PyResult<Option<R>> {
        match self.cell.get(py) {
            None => Ok(None),
            Some(obj) => Ok(Some(f(&*obj.try_borrow(py)?)?)),
        }
    }

    /// Run `f` on the object mutably, creating it if needed.
    pub fn with_mut<R>(
        &self,
        py: Python<'_>,
        f: impl FnOnce(&mut T) -> PyResult<R>,
    ) -> PyResult<R> {
        let obj = self.get(py)?;
        let mut guard = obj.try_borrow_mut(py)?;
        f(&mut *guard)
    }

    /// A deep copy (the copied object is a new Python object).
    pub fn deep_copy(&self, py: Python<'_>) -> PyResult<Self> {
        let mut copy = Slot::default();
        if let Some(obj) = self.cell.get(py) {
            let inner = obj.try_borrow(py)?.props_copy(py)?;
            let _ = copy.cell.set(py, Py::new(py, inner)?);
            copy.assigned = self.assigned;
        }
        Ok(copy)
    }
}

impl<T: Build> Slot<T> {
    /// The built value if the slot is active.
    pub fn build(&self, py: Python<'_>) -> PyResult<Option<T::Rust>> {
        if !self.active(py) {
            return Ok(None);
        }
        match self.cell.get(py) {
            None => Ok(None),
            Some(obj) => Ok(Some(obj.try_borrow(py)?.build(py)?)),
        }
    }
}

/// Coerce every item of a list for a list-valued property (None stays None).
pub fn coerce_list<T: Node>(items: Vec<Bound<'_, PyAny>>) -> PyResult<Vec<Option<Py<T>>>> {
    items.iter().map(|item| T::coerce(item)).collect()
}

/// Deep-copy a list of optional objects.
pub fn copy_list<T: Node>(py: Python<'_>, items: &[Option<Py<T>>]) -> PyResult<Vec<Option<Py<T>>>> {
    items
        .iter()
        .map(|item| match item {
            None => Ok(None),
            Some(obj) => Ok(Some(Py::new(py, obj.try_borrow(py)?.props_copy(py)?)?)),
        })
        .collect()
}

