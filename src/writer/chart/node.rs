/// Support generated by [`chart_props!`].
pub trait Props: Sized {
    /// A new object with default settings.
    fn fresh() -> Self;

    /// Set one property from a keyword argument.
    fn apply_one(&mut self, py: Python<'_>, key: &str, value: &Bound<'_, PyAny>) -> PyResult<()>;

    /// True if every generated property still has its default value.
    fn props_is_default(&self, py: Python<'_>) -> bool;

    /// A deep copy of the generated properties (nested objects are copied too).
    fn props_copy(&self, py: Python<'_>) -> PyResult<Self>;

    /// `name=value` strings for every property that differs from its default.
    fn props_repr(&self, py: Python<'_>) -> PyResult<Vec<String>>;

    /// Apply `**kwargs` as property assignments.
    fn apply_kwargs(&mut self, py: Python<'_>, kwargs: Option<&Bound<'_, PyDict>>) -> PyResult<()> {
        if let Some(kwargs) = kwargs {
            for (key, value) in kwargs.iter() {
                let key: String = key.extract()?;
                self.apply_one(py, &key, &value)?;
            }
        }
        Ok(())
    }
}

/// A chart class that can live in a [`Slot`] of another chart class.
pub trait Node: Props + PyClass<Frozen = False> + Into<PyClassInitializer<Self>> {
    /// True if the object would not change anything when applied.
    fn is_default(&self, py: Python<'_>) -> bool {
        self.props_is_default(py)
    }

    /// Convert a value assigned to a slot. `None` resets the slot.
    /// The default accepts an instance of the class or a dict of its properties.
    fn coerce(value: &Bound<'_, PyAny>) -> PyResult<Option<Py<Self>>> {
        coerce_default::<Self>(value)
    }
}

/// A chart class that builds a standalone `rust_xlsxwriter` value.
pub trait Build: Node {
    type Rust;
    fn build(&self, py: Python<'_>) -> PyResult<Self::Rust>;
}

/// The default [`Node::coerce`]: None, an instance, or a dict of properties.
pub fn coerce_default<T: Node>(value: &Bound<'_, PyAny>) -> PyResult<Option<Py<T>>> {
    let py = value.py();
    if value.is_none() {
        return Ok(None);
    }
    if let Ok(obj) = value.cast::<T>() {
        return Ok(Some(obj.clone().unbind()));
    }
    if let Ok(dict) = value.cast::<PyDict>() {
        let mut obj = T::fresh();
        obj.apply_kwargs(py, Some(dict))?;
        return Ok(Some(Py::new(py, obj)?));
    }
    Err(PyTypeError::new_err(format!(
        "expected a {} or a dict of its properties, not {}",
        T::type_object(py).name()?,
        value.get_type().name()?
    )))
}

/// Construct an object from `**kwargs`.
pub fn new_with<T: Props>(py: Python<'_>, kwargs: Option<&Bound<'_, PyDict>>) -> PyResult<T> {
    let mut obj = T::fresh();
    obj.apply_kwargs(py, kwargs)?;
    Ok(obj)
}

/// `ClassName(a=1, b=2)`.
pub fn repr_of(name: &str, parts: Vec<String>) -> String {
    format!("{name}({})", parts.join(", "))
}

/// Strip the `r#` of a raw identifier used as a property name.
pub fn pyname(name: &'static str) -> &'static str {
    name.strip_prefix("r#").unwrap_or(name)
}

/// Extract a property value, naming the property in type errors.
pub fn extract_prop<'py, T>(value: &Bound<'py, PyAny>, owner: &str, name: &str) -> PyResult<T>
where
    T: for<'a> FromPyObject<'a, 'py>,
{
    value.extract::<T>().map_err(|e| {
        let e: PyErr = e.into();
        let py = value.py();
        if e.is_instance_of::<PyTypeError>(py) {
            PyTypeError::new_err(format!("{owner}.{}: {}", pyname_dyn(name), e.value(py)))
        } else {
            e
        }
    })
}

fn pyname_dyn(name: &str) -> &str {
    name.strip_prefix("r#").unwrap_or(name)
}

