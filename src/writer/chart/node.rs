//! Shared machinery for the chart classes.
//!
//! Every chart class keeps its scalar settings in a plain `spec` struct (the
//! single source of truth) and its nested objects in [`Slot`]s. Nothing is
//! built until the chart is inserted: then the tree of Python objects is
//! walked and turned into `rust_xlsxwriter` values.
//!
//! Nested objects are *live*: `chart.x_axis` always returns the same Python
//! object, so `chart.x_axis.min = 0` changes the chart. A slot is created
//! lazily on first access and is *used* when it was assigned explicitly or
//! when any of its properties differs from the default.
//!
//! [`chart_props!`] generates the Python properties, keyword-argument
//! handling, default detection, deep copies and `repr()` support of a class.

use chrono::{NaiveDate, NaiveDateTime};
use pyo3::exceptions::PyTypeError;
use pyo3::prelude::*;
use pyo3::pyclass::boolean_struct::False;
use pyo3::sync::PyOnceLock;
use pyo3::types::{PyDate, PyDateTime, PyDict, PyString, PyTuple};
use pyo3::{IntoPyObjectExt, PyClass, PyClassInitializer};
use rust_xlsxwriter::ChartRange as RChartRange;

use crate::common::cellref::{MAX_COLS, MAX_ROWS, cell_name, col_to_name};
use crate::common::errors::{param_err, range_err};
use crate::common::value::naive_datetime;

