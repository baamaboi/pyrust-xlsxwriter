/// Generate Python properties for a chart class.
///
/// ```ignore
/// chart_props!(ChartLine
///     fields {
///         /// Docstring.
///         color: Option<Color>,
///         width: Option<f64> => check_line_width,   // validated
///         type_ as r#type: Option<T>,                // Python name differs
///     }
///     children { format: ChartFormat }               // live nested objects (Slot<T>)
///     custom { border }                              // fn get_border(&self, py) / fn set_border(&mut self, py, v)
/// );
/// ```
///
/// `fields` read/write `self.spec.<field>`; `children` are `Slot<T>` struct
/// fields; `custom` delegate to hand-written `get_<name>(&self, py) ->
/// PyResult<impl IntoPyObject>` and `set_<name>(&mut self, py, value) ->
/// PyResult<()>` (the setter's value type drives the conversion).
macro_rules! chart_props {
    (
        $ty:ident
        fields { $( $(#[$fm:meta])* $f:ident $(as $fpy:ident)? : $ft:ty $(=> $check:path)? ),* $(,)? }
        children { $( $(#[$cm:meta])* $c:ident : $ct:ty ),* $(,)? }
        custom { $( $(#[$um:meta])* $u:ident ),* $(,)? }
    ) => {
        $( chart_field!($ty [$($fm)*] $f $(as $fpy)? : $ft [$($check)?]); )*
        $( chart_child!($ty [$($cm)*] $c : $ct); )*
        $( chart_custom!($ty [$($um)*] $u); )*

        impl $crate::writer::chart::node::Props for $ty {
            fn fresh() -> Self {
                <Self as Default>::default()
            }

            #[allow(unused_variables)]
            fn apply_one(
                &mut self,
                py: pyo3::Python<'_>,
                key: &str,
                value: &pyo3::Bound<'_, pyo3::PyAny>,
            ) -> pyo3::PyResult<()> {
                $(
                    if key == chart_pyname!($f $(as $fpy)?) {
                        let v: $ft = $crate::writer::chart::node::extract_prop(value, stringify!($ty), key)?;
                        $( $check(key, &v)?; )?
                        self.spec.$f = v;
                        return Ok(());
                    }
                )*
                $(
                    if key == stringify!($c) {
                        return self.$c.assign(Some(value));
                    }
                )*
                $(
                    if key == stringify!($u) {
                        return paste::paste! {
                            self.[<set_ $u>](py, $crate::writer::chart::node::extract_prop(value, stringify!($ty), key)?)
                        };
                    }
                )*
                Err(pyo3::exceptions::PyTypeError::new_err(format!(
                    "{}() got an unexpected keyword argument '{}'",
                    stringify!($ty),
                    key
                )))
            }

            #[allow(unused_variables)]
            fn props_is_default(&self, py: pyo3::Python<'_>) -> bool {
                let fresh = <Self as $crate::writer::chart::node::Props>::fresh();
                let _ = &fresh;
                true $( && self.spec.$f == fresh.spec.$f )* $( && !self.$c.active(py) )*
            }

            #[allow(unused_variables)]
            fn props_copy(&self, py: pyo3::Python<'_>) -> pyo3::PyResult<Self> {
                #[allow(unused_mut)]
                let mut copy = <Self as $crate::writer::chart::node::Props>::fresh();
                $( copy.spec.$f = self.spec.$f.clone(); )*
                $( copy.$c = self.$c.deep_copy(py)?; )*
                Ok(copy)
            }

            #[allow(unused_variables)]
            fn props_repr(&self, py: pyo3::Python<'_>) -> pyo3::PyResult<Vec<String>> {
                use pyo3::types::PyAnyMethods;
                let fresh = <Self as $crate::writer::chart::node::Props>::fresh();
                let _ = &fresh;
                #[allow(unused_mut)]
                let mut parts: Vec<String> = Vec::new();
                $(
                    if self.spec.$f != fresh.spec.$f {
                        let value = pyo3::IntoPyObjectExt::into_bound_py_any(self.spec.$f.clone(), py)?;
                        parts.push(format!("{}={}", chart_pyname!($f $(as $fpy)?), value.repr()?));
                    }
                )*
                $(
                    if self.$c.active(py) {
                        let obj = self.$c.get(py)?;
                        parts.push(format!("{}={}", stringify!($c), obj.bind(py).repr()?));
                    }
                )*
                Ok(parts)
            }
        }
    };
}

/// The Python name of a field.
macro_rules! chart_pyname {
    ($f:ident) => {
        stringify!($f)
    };
    ($f:ident as $py:ident) => {
        $crate::writer::chart::node::pyname(stringify!($py))
    };
}

/// Getter and setter of a `spec` field (one `#[pymethods]` block each).
macro_rules! chart_field {
    ($ty:ident [$($m:meta)*] $f:ident : $ft:ty [$($check:path)?]) => {
        chart_field!($ty [$($m)*] $f as $f : $ft [$($check)?]);
    };
    ($ty:ident [$($m:meta)*] $f:ident as $py:ident : $ft:ty [$($check:path)?]) => {
        paste::paste! {
            #[pyo3::pymethods]
            impl $ty {
                $(#[$m])*
                #[getter($py)]
                fn [<pyget_ $f>](&self) -> $ft {
                    self.spec.$f.clone()
                }

                #[setter($py)]
                fn [<pyset_ $f>](&mut self, value: $ft) -> pyo3::PyResult<()> {
                    $( $check($crate::writer::chart::node::pyname(stringify!($py)), &value)?; )?
                    self.spec.$f = value;
                    Ok(())
                }
            }
        }
    };
}

/// Getter and setter of a live nested object.
macro_rules! chart_child {
    ($ty:ident [$($m:meta)*] $c:ident : $ct:ty) => {
        paste::paste! {
            #[pyo3::pymethods]
            impl $ty {
                $(#[$m])*
                #[getter($c)]
                fn [<pyget_ $c>](&self, py: pyo3::Python<'_>) -> pyo3::PyResult<pyo3::Py<$ct>> {
                    self.$c.get(py)
                }

                #[setter($c)]
                fn [<pyset_ $c>](&mut self, value: Option<&pyo3::Bound<'_, pyo3::PyAny>>) -> pyo3::PyResult<()> {
                    self.$c.assign(value)
                }
            }
        }
    };
}

/// Getter and setter delegating to `get_<name>` / `set_<name>`.
macro_rules! chart_custom {
    ($ty:ident [$($m:meta)*] $u:ident) => {
        paste::paste! {
            #[pyo3::pymethods]
            impl $ty {
                $(#[$m])*
                #[getter($u)]
                fn [<pyget_ $u>](&self, py: pyo3::Python<'_>) -> pyo3::PyResult<pyo3::Py<pyo3::PyAny>> {
                    pyo3::IntoPyObjectExt::into_py_any(self.[<get_ $u>](py)?, py)
                }

                #[setter($u)]
                fn [<pyset_ $u>](
                    &mut self,
                    py: pyo3::Python<'_>,
                    value: Option<&pyo3::Bound<'_, pyo3::PyAny>>,
                ) -> pyo3::PyResult<()> {
                    let none = py.None();
                    let value = value.unwrap_or(none.bind(py));
                    self.[<set_ $u>](
                        py,
                        $crate::writer::chart::node::extract_prop(value, stringify!($ty), stringify!($u))?,
                    )
                }
            }
        }
    };
}

