/// A `datetime.date` or naive `datetime.datetime` (dates read back as datetimes).
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct ChartDate(pub NaiveDateTime);

impl<'a, 'py> FromPyObject<'a, 'py> for ChartDate {
    type Error = PyErr;

    fn extract(obj: Borrowed<'a, 'py, PyAny>) -> Result<Self, Self::Error> {
        if let Ok(dt) = obj.cast::<PyDateTime>() {
            return Ok(ChartDate(naive_datetime(&dt)?));
        }
        if obj.cast::<PyDate>().is_ok() {
            let date: NaiveDate = obj.extract()?;
            return Ok(ChartDate(date.and_time(chrono::NaiveTime::MIN)));
        }
        Err(PyTypeError::new_err(format!(
            "expected a datetime.date or datetime.datetime, not {}",
            obj.get_type().name()?
        )))
    }
}

impl<'py> IntoPyObject<'py> for ChartDate {
    type Target = PyAny;
    type Output = Bound<'py, PyAny>;
    type Error = PyErr;

    fn into_pyobject(self, py: Python<'py>) -> Result<Self::Output, Self::Error> {
        self.0.into_bound_py_any(py)
    }
}

// ---------------------------------------------------------------------------
// Validators: `fn(name, &value) -> PyResult<()>`.
// ---------------------------------------------------------------------------

pub fn check_percent(name: &str, value: &u8) -> PyResult<()> {
    if *value > 100 {
        return Err(param_err(format!(
            "{name} must be between 0 and 100, got {value}"
        )));
    }
    Ok(())
}

fn check_f64_range(name: &str, value: Option<f64>, min: f64, max: f64) -> PyResult<()> {
    if let Some(v) = value
        && (!v.is_finite() || v < min || v > max)
    {
        return Err(param_err(format!(
            "{name} must be between {min} and {max}, got {v}"
        )));
    }
    Ok(())
}

pub fn check_line_width(name: &str, value: &Option<f64>) -> PyResult<()> {
    check_f64_range(name, *value, 0.0, 1584.0)
}

pub fn check_font_size(name: &str, value: &Option<f64>) -> PyResult<()> {
    check_f64_range(name, *value, 1.0, 409.0)
}

pub fn check_non_negative(name: &str, value: &Option<f64>) -> PyResult<()> {
    check_f64_range(name, *value, 0.0, f64::MAX)
}

pub fn check_finite(name: &str, value: &Option<f64>) -> PyResult<()> {
    check_f64_range(name, *value, f64::MIN, f64::MAX)
}

pub fn check_fraction_pair(name: &str, value: &Option<(f64, f64)>) -> PyResult<()> {
    if let Some((a, b)) = value {
        check_f64_range(name, Some(*a), 0.0, 1.0)?;
        check_f64_range(name, Some(*b), 0.0, 1.0)?;
    }
    Ok(())
}

pub fn check_angle(name: &str, value: &Option<u16>) -> PyResult<()> {
    if let Some(v) = value
        && *v >= 360
    {
        return Err(param_err(format!(
            "{name} must be between 0 and 359, got {v}"
        )));
    }
    Ok(())
}

pub fn check_font_rotation(name: &str, value: &Option<i16>) -> PyResult<()> {
    if let Some(v) = value
        && !(matches!(v, -90..=90 | 270 | 271))
    {
        return Err(param_err(format!(
            "{name} must be between -90 and 90 (or 270/271 for stacked text), got {v}"
        )));
    }
    Ok(())
}

pub fn check_marker_size(name: &str, value: &Option<u8>) -> PyResult<()> {
    if let Some(v) = value
        && !(2..=72).contains(v)
    {
        return Err(param_err(format!(
            "{name} must be between 2 and 72, got {v}"
        )));
    }
    Ok(())
}

pub fn check_separator(name: &str, value: &Option<char>) -> PyResult<()> {
    if let Some(v) = value
        && !",;. \n".contains(*v)
    {
        return Err(param_err(format!(
            "{name} must be one of ',', ';', '.', ' ' or '\\n', got {v:?}"
        )));
    }
    Ok(())
}

/// A series values/categories range must name a worksheet.
pub fn check_data_range(name: &str, value: &Option<RangeSpec>) -> PyResult<()> {
    if let Some(RangeSpec::Text(text)) = value {
        let formula = text.starts_with("=(") || text.contains('[');
        if !formula && !text.contains('!') {
            return Err(param_err(format!(
                "{name} must include a sheet name, e.g. '=Sheet1!$A$1:$A$5' or \
                 ('Sheet1', 0, 0, 4, 0), got {text:?}"
            )));
        }
    }
    Ok(())
}

pub fn check_overlap(name: &str, value: &Option<i8>) -> PyResult<()> {
    if let Some(v) = value
        && !(-100..=100).contains(v)
    {
        return Err(param_err(format!(
            "{name} must be between -100 and 100, got {v}"
        )));
    }
    Ok(())
}

pub fn check_gap(name: &str, value: &Option<u16>) -> PyResult<()> {
    if let Some(v) = value
        && *v > 500
    {
        return Err(param_err(format!(
            "{name} must be between 0 and 500, got {v}"
        )));
    }
    Ok(())
}

pub fn check_log_base(name: &str, value: &Option<u16>) -> PyResult<()> {
    if let Some(v) = value
        && *v < 2
    {
        return Err(param_err(format!("{name} must be 2 or more, got {v}")));
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn range_specs_convert_to_chart_ranges() {
        let text = RangeSpec::Text("=Sheet1!$A$1:$A$5".to_string());
        assert!(text.to_rust() == RChartRange::new_from_string("=Sheet1!$A$1:$A$5"));
        let cell = RangeSpec::Cell("Sheet1".to_string(), 2, 1);
        assert!(cell.to_rust() == RChartRange::new_from_range("Sheet1", 2, 1, 2, 1));
        let range = RangeSpec::Range("My Data".to_string(), 0, 0, 4, 2);
        assert!(range.to_rust() == RChartRange::new_from_range("My Data", 0, 0, 4, 2));
    }

    #[test]
    fn range_specs_display_as_formulas() {
        assert_eq!(RangeSpec::Text("Sales".to_string()).display(), "Sales");
        assert_eq!(
            RangeSpec::Cell("Sheet1".to_string(), 0, 1).display(),
            "=Sheet1!$B$1"
        );
        assert_eq!(
            RangeSpec::Range("My Data".to_string(), 0, 0, 4, 2).display(),
            "='My Data'!$A$1:$C$5"
        );
    }

    #[test]
    fn raw_property_names() {
        assert_eq!(pyname("r#type"), "type");
        assert_eq!(pyname("color"), "color");
    }

    #[test]
    fn validators_accept_valid_values() {
        assert!(check_percent("p", &100).is_ok());
        assert!(check_line_width("w", &Some(1584.0)).is_ok());
        assert!(check_line_width("w", &None).is_ok());
        assert!(check_angle("a", &Some(359)).is_ok());
        assert!(check_font_rotation("r", &Some(-90)).is_ok());
        assert!(check_font_rotation("r", &Some(271)).is_ok());
        assert!(check_marker_size("s", &Some(72)).is_ok());
        assert!(check_separator("s", &Some('\n')).is_ok());
        assert!(check_fraction_pair("o", &Some((0.0, 1.0))).is_ok());
        assert!(check_overlap("o", &Some(-100)).is_ok());
        assert!(check_gap("g", &Some(500)).is_ok());
        assert!(check_log_base("l", &Some(2)).is_ok());
        let formula = Some(RangeSpec::Text("=(Sheet1!$A$1,Sheet1!$A$3)".to_string()));
        assert!(check_data_range("values", &formula).is_ok());
        let tuple = Some(RangeSpec::Range("Sheet1".to_string(), 0, 0, 4, 0));
        assert!(check_data_range("values", &tuple).is_ok());
    }
}
